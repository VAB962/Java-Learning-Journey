package Operators;

public class AssignmentOperator {

    public static void main (String[] args){

        int a=10;
        System.out.println("Initial:"+a);       //10

        a+=10;
        System.out.println("Initial:"+a);       //20

        a-=10;
        System.out.println("Initial:"+a);       //10

        a*=10;
        System.out.println("Initial:"+a);       //100

        a/=10;
        System.out.println("Initial:"+a);       //10

        a%=10;
        System.out.println("Initial:"+a);       //0
    }
}
